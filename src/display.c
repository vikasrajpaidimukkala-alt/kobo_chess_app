int display_init(Display *d)
{
    size_t required;
    int rc;

    memset(d, 0, sizeof(*d));
    d->fbfd = -1;
    d->cfg.is_quiet = true;

    d->fbfd = fbink_open();
    if (d->fbfd < 0) {
        fprintf(stderr, "fbink_open() failed: %d\n", d->fbfd);
        return -1;
    }

    rc = fbink_init(d->fbfd, &d->cfg);
    if (rc < 0) {
        fprintf(stderr, "fbink_init() failed: %d\n", rc);
        fbink_close(d->fbfd);
        d->fbfd = -1;
        return -1;
    }

    fbink_get_state(&d->cfg, &d->state);

    d->width = d->state.screen_width;
    d->height = d->state.screen_height;
    d->stride = d->state.scanline_stride;
    d->color = d->state.has_color_panel;

    fprintf(stderr, "Device: %s (%s)\n",
            d->state.device_name, d->state.device_codename);
    fprintf(stderr, "Screen: %u x %u, stride %u, bpp %u, fmt %u, color %d, mtk %d\n",
            d->width, d->height, d->stride, d->state.bpp,
            d->state.pixel_format, (int)d->color, (int)d->state.is_mtk);

    if (d->state.bpp != 32) {
        fprintf(stderr, "Need a 32-bit framebuffer (got %u bpp)\n", d->state.bpp);
        fbink_close(d->fbfd);
        d->fbfd = -1;
        return -1;
    }

    d->fb = fbink_get_fb_pointer(d->fbfd, &d->fb_size);
    if (d->fb == NULL) {
        fprintf(stderr, "fbink_get_fb_pointer() failed\n");
        fbink_close(d->fbfd);
        d->fbfd = -1;
        return -1;
    }

    required = (size_t)d->stride * d->height;
    if (d->fb_size < required) {
        fprintf(stderr, "Framebuffer too small: %zu < %zu\n", d->fb_size, required);
        fbink_close(d->fbfd);
        d->fbfd = -1;
        return -1;
    }

    return 0;
}

void display_close(Display *d)
{
    if (d->fbfd >= 0) {
        fbink_close(d->fbfd);
        d->fbfd = -1;
    }

    d->fb = NULL;
}

void display_put(Display *d, int x, int y, uint8_t r, uint8_t g, uint8_t b)
{
    unsigned char *pixel;

    if ((unsigned)x >= d->width || (unsigned)y >= d->height) {
        return;
    }

    pixel = d->fb + ((size_t)y * d->stride) + ((size_t)x * 4);

    if (d->state.pixel_format == FBINK_PXFMT_BGRA ||
        d->state.pixel_format == FBINK_PXFMT_BGR32) {
        pixel[0] = b;
        pixel[1] = g;
        pixel[2] = r;
        pixel[3] = 0xFF;
        return;
    }

    /* RGBA, as on Libra Colour (see src/fb_direct_test.c). */
    pixel[0] = r;
    pixel[1] = g;
    pixel[2] = b;
    pixel[3] = 0xFF;
}

void display_fill_rect(Display *d, int x, int y, int w, int h,
                       uint8_t r, uint8_t g, uint8_t b)
{
    int yy;
    int xx;
    int x0 = x;
    int y0 = y;
    int x1 = x + w;
    int y1 = y + h;
    int b0 = b;
    int g0 = g;
    int r0 = r;
    bool bgra;

    if (x0 < 0) {
        x0 = 0;
    }
    if (y0 < 0) {
        y0 = 0;
    }
    if (x1 > (int)d->width) {
        x1 = (int)d->width;
    }
    if (y1 > (int)d->height) {
        y1 = (int)d->height;
    }

    bgra = (d->state.pixel_format == FBINK_PXFMT_BGRA ||
            d->state.pixel_format == FBINK_PXFMT_BGR32);

    for (yy = y0; yy < y1; yy++) {
        unsigned char *pixel =
            d->fb + ((size_t)yy * d->stride) + ((size_t)x0 * 4);

        for (xx = x0; xx < x1; xx++) {
            if (bgra) {
                pixel[0] = (unsigned char)b0;
                pixel[1] = (unsigned char)g0;
                pixel[2] = (unsigned char)r0;
            } else {
                pixel[0] = (unsigned char)r0;
                pixel[1] = (unsigned char)g0;
                pixel[2] = (unsigned char)b0;
            }
            pixel[3] = 0xFF;
            pixel += 4;
        }
    }
}

void display_fill_circle(Display *d, int cx, int cy, int radius,
                         uint8_t r, uint8_t g, uint8_t b)
{
    int y;
    int rr = radius * radius;

    for (y = -radius; y <= radius; y++) {
        int x;
        int yy = y * y;

        for (x = -radius; x <= radius; x++) {
            if (x * x + yy <= rr) {
                display_put(d, cx + x, cy + y, r, g, b);
            }
        }
    }
}

void display_stroke_circle(Display *d, int cx, int cy, int radius, int t,
                           uint8_t r, uint8_t g, uint8_t b)
{
    int y;
    int r2 = radius * radius;
    int inner = radius - t;
    int i2 = (inner < 0) ? 0 : inner * inner;

    for (y = -radius; y <= radius; y++) {
        int x;
        int yy = y * y;

        for (x = -radius; x <= radius; x++) {
            int d2 = x * x + yy;

            if (d2 <= r2 && d2 >= i2) {
                display_put(d, cx + x, cy + y, r, g, b);
            }
        }
    }
}

void display_clear(Display *d, uint8_t r, uint8_t g, uint8_t b)
{
    display_fill_rect(d, 0, 0, (int)d->width, (int)d->height, r, g, b);
}

void display_hline(Display *d, int x0, int x1, int y, int t,
                   uint8_t r, uint8_t g, uint8_t b)
{
    if (x1 < x0) {
        int tmp = x0;
        x0 = x1;
        x1 = tmp;
    }

    display_fill_rect(d, x0, y, x1 - x0 + 1, t, r, g, b);
}

void display_vline(Display *d, int x, int y0, int y1, int t,
                   uint8_t r, uint8_t g, uint8_t b)
{
    if (y1 < y0) {
        int tmp = y0;
        y0 = y1;
        y1 = tmp;
    }

    display_fill_rect(d, x, y0, t, y1 - y0 + 1, r, g, b);
}

static const unsigned char *glyph_for(char c)
{
    unsigned char u = (unsigned char)c;

    if (u < 32 || u > 127) {
        u = '?';
    }

    return FONT8[u - 32];
}

int display_text_width(const char *s, int scale)
{
    return (int)strlen(s) * 8 * scale;
}

int display_text_height(int scale)
{
    return 8 * scale;
}

void display_text(Display *d, int x, int y, int scale, const char *s,
                  uint8_t r, uint8_t g, uint8_t b)
{
    int cx = x;
    int i;

    if (scale < 1) {
        scale = 1;
    }

    for (i = 0; s[i] != '\0'; i++) {
        const unsigned char *gly = glyph_for(s[i]);
        int row;
        int col;

        for (row = 0; row < 8; row++) {
            unsigned char bits = gly[row];
            for (col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    display_fill_rect(d,
                                      cx + col * scale,
                                      y + row * scale,
                                      scale, scale, r, g, b);
                }
            }
        }

        cx += 8 * scale;
    }
}

void display_refresh(Display *d, int x, int y, int w, int h,
                     WFM_MODE_INDEX_T wfm, bool flash)
{
    FBInkRect rect;
    FBInkConfig cfg = d->cfg;
    int rc;

    if (x < 0) {
        w += x;
        x = 0;
    }
    if (y < 0) {
        h += y;
        y = 0;
    }
    if (x + w > (int)d->width) {
        w = (int)d->width - x;
    }
    if (y + h > (int)d->height) {
        h = (int)d->height - y;
    }
    if (w <= 0 || h <= 0) {
        return;
    }

    rect.left = (unsigned short)x;
    rect.top = (unsigned short)y;
    rect.width = (unsigned short)w;
    rect.height = (unsigned short)h;

    cfg.wfm_mode = wfm;
    cfg.is_flashing = flash;

    rc = fbink_refresh_rect(d->fbfd, &rect, &cfg);
    if (rc < 0) {
        fprintf(stderr, "fbink_refresh_rect() failed: %d\n", rc);
    }
}

void display_refresh_full(Display *d, bool flash)
{
    WFM_MODE_INDEX_T wfm = d->color ? WFM_GCC16 : WFM_GC16;

    display_refresh(d, 0, 0, (int)d->width, (int)d->height, wfm, flash);
}
