/*
 * Software rasteriser. No device knowledge lives here: it fills bytes
 * in a Canvas and nothing else, so it is shared by every backend.
 */

bool canvas_init(Canvas *c, unsigned int width, unsigned int height)
{
    memset(c, 0, sizeof(*c));

    c->width = width;
    c->height = height;
    c->stride = width * 4U;
    c->len = (size_t)c->stride * height;
    c->pix = malloc(c->len);
    if (c->pix == NULL) {
        return false;
    }

    memset(c->pix, 0xFF, c->len);
    return true;
}

void canvas_free(Canvas *c)
{
    free(c->pix);
    c->pix = NULL;
    c->len = 0;
}

