void canvas_put(Canvas *c, int x, int y, uint8_t r, uint8_t g, uint8_t b)
{
    unsigned char *pixel;

    if ((unsigned)x >= c->width || (unsigned)y >= c->height) {
        return;
    }

    pixel = c->pix + ((size_t)y * c->stride) + ((size_t)x * 4);
    pixel[0] = r;
    pixel[1] = g;
    pixel[2] = b;
    pixel[3] = 0xFF;
}

void canvas_fill_rect(Canvas *c, int x, int y, int w, int h,
                       uint8_t r, uint8_t g, uint8_t b)
{
    int yy;
    int xx;
    int x0 = x;
    int y0 = y;
    int x1 = x + w;
    int y1 = y + h;

    if (x0 < 0) {
        x0 = 0;
    }
    if (y0 < 0) {
        y0 = 0;
    }
    if (x1 > (int)c->width) {
        x1 = (int)c->width;
    }
    if (y1 > (int)c->height) {
        y1 = (int)c->height;
    }

    for (yy = y0; yy < y1; yy++) {
        unsigned char *pixel =
            c->pix + ((size_t)yy * c->stride) + ((size_t)x0 * 4);

        for (xx = x0; xx < x1; xx++) {
            pixel[0] = r;
            pixel[1] = g;
            pixel[2] = b;
            pixel[3] = 0xFF;
            pixel += 4;
        }
    }
}

void canvas_fill_circle(Canvas *c, int cx, int cy, int radius,
                         uint8_t r, uint8_t g, uint8_t b)
{
    int y;
    int rr = radius * radius;

    for (y = -radius; y <= radius; y++) {
        int x;
        int yy = y * y;

        for (x = -radius; x <= radius; x++) {
            if (x * x + yy <= rr) {
                canvas_put(c, cx + x, cy + y, r, g, b);
            }
        }
    }
}

void canvas_stroke_circle(Canvas *c, int cx, int cy, int radius, int t,
                           uint8_t r, uint8_t g, uint8_t b)
{
    int y;
    int r2 = radius * radius;
    int inner = radius - t;
    int i2 = (inner < 0) ? 0 : inner * inner;

    for (y = -radius; y <= radius; y++) {
        int x;
        int yy = y * y;

        for (x = -radius; x <= radius; x++) {
            int d2 = x * x + yy;

            if (d2 <= r2 && d2 >= i2) {
                canvas_put(c, cx + x, cy + y, r, g, b);
            }
        }
    }
}

void canvas_clear(Canvas *c, uint8_t r, uint8_t g, uint8_t b)
{
    canvas_fill_rect(c, 0, 0, (int)c->width, (int)c->height, r, g, b);
}

void canvas_hline(Canvas *c, int x0, int x1, int y, int t,
                   uint8_t r, uint8_t g, uint8_t b)
{
    if (x1 < x0) {
        int tmp = x0;
        x0 = x1;
        x1 = tmp;
    }

    canvas_fill_rect(c, x0, y, x1 - x0 + 1, t, r, g, b);
}

void canvas_vline(Canvas *c, int x, int y0, int y1, int t,
                   uint8_t r, uint8_t g, uint8_t b)
{
    if (y1 < y0) {
        int tmp = y0;
        y0 = y1;
        y1 = tmp;
    }

    canvas_fill_rect(c, x, y0, t, y1 - y0 + 1, r, g, b);
}

static const unsigned char *glyph_for(char c)
{
    unsigned char u = (unsigned char)c;

    if (u < 32 || u > 127) {
        u = '?';
    }

    return FONT8[u - 32];
}

int canvas_text_width(const char *s, int scale)
{
    return (int)strlen(s) * 8 * scale;
}

int canvas_text_height(int scale)
{
    return 8 * scale;
}

void canvas_text(Canvas *c, int x, int y, int scale, const char *s,
                  uint8_t r, uint8_t g, uint8_t b)
{
    int cx = x;
    int i;

    if (scale < 1) {
        scale = 1;
    }

    for (i = 0; s[i] != '\0'; i++) {
        const unsigned char *gly = glyph_for(s[i]);
        int row;
        int col;

        for (row = 0; row < 8; row++) {
            unsigned char bits = gly[row];
            for (col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    canvas_fill_rect(c,
                                      cx + col * scale,
                                      y + row * scale,
                                      scale, scale, r, g, b);
                }
            }
        }

        cx += 8 * scale;
    }
}
